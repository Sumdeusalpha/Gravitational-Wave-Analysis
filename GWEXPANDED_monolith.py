# build_unmatched_dbscan_clusters.py
#
# Memory-safe 1D "DBSCAN-like" clustering for unmatched ratios.
# It runs entirely on F:\ and writes unmatched_dbscan_clusters.csv there.

from pathlib import Path
import numpy as np
import pandas as pd

# ---------------------------------------------------------
# Paths – ALL on F:
# ---------------------------------------------------------
BASE_DIR = Path(r"F:\gw_constant_analysis_outputs")
flat_path = BASE_DIR / "unmatched_ratios_flat.csv"
out_path = BASE_DIR / "unmatched_dbscan_clusters.csv"

print(f"[INFO] BASE_DIR: {BASE_DIR}")
print(f"[INFO] Reading unmatched ratios from: {flat_path}")

if not flat_path.exists():
    raise FileNotFoundError(f"unmatched_ratios_flat.csv not found at {flat_path}")

# Only load what we need
df = pd.read_csv(flat_path, usecols=["Ratio"])
vals = df["Ratio"].to_numpy(dtype=float)
vals = vals[np.isfinite(vals)]

# Restrict to a reasonable range (tune if you want)
mask = (vals > 0) & (vals < 10.0)
data = vals[mask]

if data.size == 0:
    print("[WARN] No finite positive unmatched ratios in (0, 10). Writing empty file.")
    empty = pd.DataFrame(columns=["ClusterID", "Center", "Count", "Std", "Min", "Max"])
    empty.to_csv(out_path, index=False)
    raise SystemExit(0)

# ---------------------------------------------------------
# 1D "DBSCAN" by gap-based clustering
# ---------------------------------------------------------
# eps: max gap between neighboring points in same cluster
# min_pts: minimum points required for a cluster
eps = 0.02
min_pts = 30

print(f"[INFO] Clustering {data.size} points with eps={eps}, min_pts={min_pts}")

# Sort once – O(N log N), then single pass
data_sorted = np.sort(data)

clusters = []
start = 0

for i in range(1, data_sorted.size):
    if data_sorted[i] - data_sorted[i - 1] > eps:
        # cluster boundary
        end = i - 1
        length = end - start + 1
        if length >= min_pts:
            cluster_vals = data_sorted[start : end + 1]
            clusters.append(cluster_vals)
        start = i

# Handle final cluster
end = data_sorted.size - 1
length = end - start + 1
if length >= min_pts:
    cluster_vals = data_sorted[start : end + 1]
    clusters.append(cluster_vals)

# Build output table
rows = []
for cid, cluster_vals in enumerate(clusters):
    rows.append(
        {
            "ClusterID": int(cid),
            "Center": float(np.mean(cluster_vals)),
            "Count": int(cluster_vals.size),
            "Std": float(np.std(cluster_vals)),
            "Min": float(cluster_vals.min()),
            "Max": float(cluster_vals.max()),
        }
    )

if not rows:
    print("[WARN] No clusters above min_pts. Writing empty file.")
    out_df = pd.DataFrame(columns=["ClusterID", "Center", "Count", "Std", "Min", "Max"])
else:
    out_df = pd.DataFrame(rows).sort_values("Center").reset_index(drop=True)

out_df.to_csv(out_path, index=False)
print(f"[INFO] Wrote {len(out_df)} clusters to {out_path}")


