def plot_on_vs_null_constant_profiles(show: bool = False, top_n: int = 20):
    """
    ON vs OFF / null constant profiles for one representative event.

    Preferred source: constant_matches_per_segment.csv with columns like:
        - Event, Detector, Constant, WindowType (ON/OFF1/OFF2/NULL_PHASE/NULL_SHUFFLE), Count
    Fallback: constant_window_contrasts.csv (global).
    """
    seg_path = BASE_DIR / "constant_matches_per_segment.csv"
    if seg_path.exists():
        df = pd.read_csv(seg_path)

        # Guess column names
        const_col = [c for c in df.columns if c.lower() == "constant"]
        win_col = [c for c in df.columns if "window" in c.lower() or "segment" in c.lower()]
        count_candidates = [c for c in df.columns
                            if c.lower() in ("count", "matches", "n", "totalmatches")]
        event_col = [c for c in df.columns if c.lower() in ("event", "event_id", "gw_event")]
        det_col = [c for c in df.columns if c.lower() in ("detector", "ifo", "site")]

        if not (const_col and win_col and count_candidates):
            print("[on_vs_null_profiles] Could not infer column names in constant_matches_per_segment.csv.")
            print("  Columns:", list(df.columns))
            return

        const_col = const_col[0]
        win_col = win_col[0]
        count_col = count_candidates[0]
        event_col = event_col[0] if event_col else None
        det_col = det_col[0] if det_col else None

        # Choose representative event/detector by ON total
        if event_col and det_col:
            df_on = df[df[win_col].str.upper() == "ON"]
            if df_on.empty:
                print("[on_vs_null_profiles] No ON rows in segment file.")
                return
            df_on["TotalOnForPair"] = df_on.groupby([event_col, det_col])[count_col].transform("sum")
            idx = df_on["TotalOnForPair"].idxmax()
            row = df_on.loc[idx]
            event_val = row[event_col]
            det_val = row[det_col]
            sub = df[(df[event_col] == event_val) & (df[det_col] == det_val)]
            title_suffix = f"{event_val} ({det_val})"
        else:
            sub = df.copy()
            title_suffix = "representative event"

        # Restrict to top constants by ON count
        on_sub = sub[sub[win_col].str.upper() == "ON"]
        top_consts = (
            on_sub.groupby(const_col)[count_col].sum()
            .sort_values(ascending=False)
            .head(top_n)
            .index.tolist()
        )
        sub = sub[sub[const_col].isin(top_consts)]

        pivot = sub.pivot_table(
            index=const_col,
            columns=win_col,
            values=count_col,
            aggfunc="sum",
            fill_value=0,
        )

        pivot = pivot.reindex(top_consts)

        fig, ax = plt.subplots(figsize=(7, 4))
        pivot.plot(kind="bar", ax=ax)
        ax.set_xlabel("Constant")
        ax.set_ylabel("Match count per segment type")
        ax.set_title(f"Constant match profiles for ON vs OFF and null – {title_suffix}")
        ax.legend(title="Segment type", fontsize=8)
        plt.xticks(rotation=75, ha="right")
        _save_and_maybe_show(fig, "on_vs_null_constant_profiles.png", show=show)
        return

    # Fallback: use global contrasts
    contrast_path = BASE_DIR / "constant_window_contrasts.csv"
    if contrast_path.exists():
        df = pd.read_csv(contrast_path)
        if "Constant" not in df.columns:
            print("[on_vs_null_profiles] No 'Constant' column in constant_window_contrasts.csv.")
            return

        cols = [c for c in df.columns if c.startswith("ON_vs_")]
        if not cols:
            print("[on_vs_null_profiles] No ON_vs_* columns in constant_window_contrasts.csv.")
            return

        # Show only a couple of contrasts
        df = df.sort_values(cols[0], ascending=False).head(top_n)

        fig, ax = plt.subplots(figsize=(7, 4))
        for col in cols[:3]:
            if col not in df.columns:
                continue
            ax.plot(df["Constant"], df[col], marker="o", label=col.replace("_", " "))
        ax.set_xticklabels(df["Constant"], rotation=75, ha="right")
        ax.set_ylabel("Enrichment contrast")
        ax.set_title("ON vs null constant enrichment (global contrast)")
        ax.legend(fontsize=8)
        _save_and_maybe_show(fig, "on_vs_null_constant_profiles_global.png", show=show)
        return

    print("[on_vs_null_profiles] No suitable source found (constant_matches_per_segment or constant_window_contrasts).")


