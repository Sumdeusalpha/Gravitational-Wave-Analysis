def plot_example_time_slicing_from_gwosc(
    event_id: str = "GW170817",
    detector: str = "H1",
    show: bool = False,
):
    """
    Example event time-slicing for Section 2.2.

    Fetches a 120 s strain segment around the event trigger directly
    from GWOSC, then shades:
        - Legacy window: [t_e - 60, t_e + 60]
        - Burst ON window: [t_e - 0.2, t_e + 0.1]
        - OFF1: [t_e - 50, t_e - 20]
        - OFF2: [t_e + 20, t_e + 50]

    Parameters
    ----------
    event_id : str
        GWOSC event name, e.g. "GW170817", "GW150914".
    detector : str
        Detector code, e.g. "H1" or "L1".
    show : bool
        If True, display in Jupyter as well as saving.
    """
    # Get trigger time from GWOSC
    try:
        te = gw_event.event_gps(event_id)
    except Exception as exc:
        print(f"[example_time_slicing_from_gwosc] Failed to get GPS for {event_id}: {exc}")
        return

    # Fetch 120 s of calibrated strain around the event
    try:
        ts = TimeSeries.fetch_open_data(detector, te - 60, te + 60)
    except Exception as exc:
        print(f"[example_time_slicing_from_gwosc] Failed to fetch data for {event_id} / {detector}: {exc}")
        return

    t = ts.times.value   # seconds (GPS)
    h = ts.value

    # Define windows exactly as in §2.2
    LEG = (te - 60, te + 60)
    ON = (te - 0.2, te + 0.1)
    OFF1 = (te - 50, te - 20)
    OFF2 = (te + 20, te + 50)

    fig, ax = plt.subplots(figsize=(7, 3))

    ax.plot(t, h, linewidth=0.4)
    ax.set_xlabel("Time (s, GPS)")
    ax.set_ylabel("Strain")
    ax.set_title(f"Time-sliced strain for {event_id} ({detector})")

    # Shade the windows
    ax.axvspan(LEG[0], LEG[1], color="lightgray", alpha=0.2, label="Legacy 120 s")
    ax.axvspan(ON[0], ON[1], color="green", alpha=0.35, label="Burst window (ON)")
    ax.axvspan(OFF1[0], OFF1[1], color="red", alpha=0.15, label="OFF background")
    ax.axvspan(OFF2[0], OFF2[1], color="red", alpha=0.15)

    # Limit x-range to the legacy window to keep it tidy
    ax.set_xlim(LEG[0], LEG[1])

    ax.legend(loc="upper right", fontsize=7)

    # Save with a descriptive name (no “Visual 2.2” prefix, just the content)
    filename = f"time_slicing_{event_id}_{detector}.png"
    _save_and_maybe_show(fig, filename, show=show)


