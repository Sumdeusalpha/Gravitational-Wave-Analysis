def plot_per_event_z_heatmap(z_threshold=3.0, max_constants=15, max_events=25):
    """
    Build a heatmap of |Z| for the most interesting (event, constant) pairs.
    z_threshold: only include entries with |Z| >= this
    """
    path = BASE_DIR / "per_event_z_scores.csv"
    df = pd.read_csv(path)

    df["absZ"] = df["ZScore"].abs()

    # Filter to significant cells
    sig = df[df["absZ"] >= z_threshold].copy()
    if sig.empty:
        print("[per_event_heatmap] No entries above threshold; try lowering z_threshold.")
        return

    # Select top constants & events by max |Z|
    const_order = (
        sig.groupby("Constant")["absZ"].max()
        .sort_values(ascending=False)
        .head(max_constants)
        .index.tolist()
    )
    evt_order = (
        sig.groupby("Event")["absZ"].max()
        .sort_values(ascending=False)
        .head(max_events)
        .index.tolist()
    )

    sub = sig[sig["Constant"].isin(const_order) & sig["Event"].isin(evt_order)]

    pivot = sub.pivot_table(
        index="Event",
        columns="Constant",
        values="ZScore",
        aggfunc="mean"
    )

    pivot = pivot.loc[evt_order, const_order]

    fig, ax = plt.subplots(figsize=(1.2 * len(const_order), 0.45 * len(evt_order) + 3))
    sns.heatmap(
        pivot,
        cmap="coolwarm",
        center=0.0,
        annot=False,
        ax=ax
    )
    ax.set_title(f"Per-event constant deviations (Z-score), |Z| >= {z_threshold}")
    ax.set_xlabel("Constant")
    ax.set_ylabel("Event")
    fig.tight_layout()
    fig.savefig(OUT_DIR / "vis_per_event_constant_z_heatmap.png")
    plt.close(fig)


