# Visual 2.7 – Event–Constant Z-Score Heatmap
# =====================================================================

def plot_event_constant_z_heatmap(
    z_threshold: float = 3.0,
    max_constants: int = 15,
    max_events: int = 25,
    show: bool = False,
):
    """
    Event–constant Z-score heatmap.

    Uses per_event_z_scores.csv
    """
    path = BASE_DIR / "per_event_z_scores.csv"
    if not path.exists():
        print("[event_constant_z_heatmap] per_event_z_scores.csv not found.")
        return

    df = pd.read_csv(path)
    if {"Event", "Constant", "ZScore"} - set(df.columns):
        print("[event_constant_z_heatmap] CSV must contain 'Event', 'Constant', 'ZScore'.")
        print("  Columns:", list(df.columns))
        return

    df["absZ"] = df["ZScore"].abs()
    sig = df[df["absZ"] >= z_threshold].copy()
    if sig.empty:
        print("[event_constant_z_heatmap] No entries with |Z| above threshold.")
        return

    const_order = (
        sig.groupby("Constant")["absZ"].max()
        .sort_values(ascending=False)
        .head(max_constants)
        .index.tolist()
    )
    evt_order = (
        sig.groupby("Event")["absZ"].max()
        .sort_values(ascending=False)
        .head(max_events)
        .index.tolist()
    )

    sub = sig[sig["Constant"].isin(const_order) & sig["Event"].isin(evt_order)]
    pivot = sub.pivot_table(
        index="Event",
        columns="Constant",
        values="ZScore",
        aggfunc="mean"
    )
    pivot = pivot.loc[evt_order, const_order]

    fig, ax = plt.subplots(
        figsize=(0.5 * len(const_order) + 4, 0.3 * len(evt_order) + 3)
    )
    sns.heatmap(pivot, cmap="coolwarm", center=0.0, annot=False, ax=ax)
    ax.set_xlabel("Constant")
    ax.set_ylabel("Event")
    ax.set_title(f"Event–constant Z-scores (|Z| ≥ {z_threshold})")
    _save_and_maybe_show(fig, "event_constant_zscore_heatmap.png", show=show)


