def plot_classifier_roc_accuracy(show: bool = False):
    """
    ROC / accuracy summary.

    Uses classifier_crossval_scores.csv and/or classifier_grouped_event_splits.csv.

    Expected structure (flexible but typical):
        classifier_crossval_scores.csv:
            SplitType (e.g., 'random'), Fold, Accuracy, (optional: ROC_AUC)
        classifier_grouped_event_splits.csv:
            SplitType (e.g., 'grouped'), Fold, Accuracy, (optional: ROC_AUC)
    """
    rand_path = BASE_DIR / "classifier_crossval_scores.csv"
    group_path = BASE_DIR / "classifier_grouped_event_splits.csv"

    records = []
    if rand_path.exists():
        df_r = pd.read_csv(rand_path)
        acc_col = "Accuracy" if "Accuracy" in df_r.columns else None
        auc_col = "ROC_AUC" if "ROC_AUC" in df_r.columns else None
        if acc_col:
            df_r["SplitCategory"] = "Random splits"
            df_r["Accuracy"] = df_r[acc_col]
            if auc_col:
                df_r["ROC_AUC"] = df_r[auc_col]
            records.append(df_r)
    if group_path.exists():
        df_g = pd.read_csv(group_path)
        acc_col = "Accuracy" if "Accuracy" in df_g.columns else None
        auc_col = "ROC_AUC" if "ROC_AUC" in df_g.columns else None
        if acc_col:
            df_g["SplitCategory"] = "Event-grouped splits"
            df_g["Accuracy"] = df_g[acc_col]
            if auc_col:
                df_g["ROC_AUC"] = df_g[auc_col]
            records.append(df_g)

    if not records:
        print("[classifier_roc_accuracy] No classifier_*scores.csv files found or no Accuracy column.")
        return

    df_all = pd.concat(records, ignore_index=True)

    # Accuracy boxplot
    fig, ax = plt.subplots(figsize=(5, 4))
    sns.boxplot(data=df_all, x="SplitCategory", y="Accuracy", ax=ax)
    ax.set_ylabel("Accuracy")
    ax.set_xlabel("")
    ax.set_title("Classifier accuracy for random vs event-grouped splits")
    _save_and_maybe_show(fig, "classifier_accuracy_summary.png", show=show)

    # ROC AUC if available
    if "ROC_AUC" in df_all.columns and not df_all["ROC_AUC"].isna().all():
        fig, ax = plt.subplots(figsize=(5, 4))
        sns.boxplot(data=df_all, x="SplitCategory", y="ROC_AUC", ax=ax)
        ax.set_ylabel("ROC AUC")
        ax.set_xlabel("")
        ax.set_title("Classifier ROC AUC for random vs event-grouped splits")
        _save_and_maybe_show(fig, "classifier_roc_auc_summary.png", show=show)


