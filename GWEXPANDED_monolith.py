def fetch_gw_data(event_name, ifo, max_retries=3):
    """
    Fetch GW strain for (event_name, ifo) with a few retries.
    If we see a partial-download/cache error, we retry once with cache=False.
    """
    for attempt in range(max_retries):
        try:
            event_data = fetch_event_json(event_name)
            gps = event_data['events'][event_name]['GPS']
            start = gps - LEGACY_WINDOW_HALF
            end = gps + LEGACY_WINDOW_HALF

            # First try using cache, then fall back to cache=False if we see trouble
            use_cache = True if attempt == 0 else False

            print(f"[fetch_gw_data] {event_name} [{ifo}] attempt {attempt+1}/{max_retries} "
                  f"(cache={use_cache})")

            strain = TimeSeries.fetch_open_data(ifo, start, end, cache=use_cache)
            return strain, gps

        except Exception as e:
            msg = str(e)
            print(f"Error fetching data for {event_name} [{ifo}] attempt {attempt+1}: {msg}")

            # If this looks like the partial-download / bad-cache problem,
            # let the next attempt run with cache=False.
            if "File was supposed to be" in msg or "Download failed" in msg:
                continue  # next loop iteration

            # Any other error: give up on this event
            break

    print(f"[fetch_gw_data] Giving up on {event_name} [{ifo}] after {max_retries} attempts.")
    return None, None

def slice_window(strain, t_start, t_end):
    if strain is None:
        return None
    mask = (strain.times.value >= t_start) & (strain.times.value <= t_end)
    if not np.any(mask):
        return None
    return TimeSeries(strain.value[mask], times=strain.times.value[mask])

