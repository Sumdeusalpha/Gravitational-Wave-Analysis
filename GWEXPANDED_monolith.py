def log_unmatched_ratios(event, detector, window_type, domain,
                         ratio_category, ratios,
                         epsilon=None):
    """
    Log ratios that do NOT match any known constant within given tolerance.
    We restrict this to REAL ON segments only (caller decides when to call).
    Also append to global unmatched_values_for_hunter for downstream analysis.
    """
    global unmatched_values_for_hunter

    if ratios is None or len(ratios) == 0:
        return
    if epsilon is None:
        epsilon = ATOL

    rows = []
    const_vals = list(known_constants.values())
    for r in ratios:
        if not any(np.isclose(r, v, rtol=RTOL, atol=epsilon) for v in const_vals):
            rows.append([
                event,
                detector,
                window_type,
                domain,
                ratio_category,
                float(r)
            ])
            unmatched_values_for_hunter.append(float(r))

    if rows:
        with open(UNMATCHED_PATH, "a", newline="") as f:
            writer = csv.writer(f)
            writer.writerows(rows)

def build_unmatched_detailed_csv():
    """
    Build a detailed unmatched ratios file that includes nearest known constant
    and distance metrics. This is Phase II diagnostic for interpretation.
    """
    if not os.path.exists(UNMATCHED_PATH):
        print("No unmatched_ratios.csv found; skipping unmatched detailed export.")
        return

    df = pd.read_csv(UNMATCHED_PATH)
    if df.empty:
        print("unmatched_ratios.csv is empty; skipping unmatched detailed export.")
        return

    rows = []
    const_items = list(known_constants.items())

    for _, row in df.iterrows():
        try:
            r_val = float(row["RatioValue"])
        except Exception:
            continue

        best_name = None
        best_val = None
        best_abs = None

        for cname, cval in const_items:
            try:
                diff = abs(r_val - float(cval))
            except Exception:
                continue
            if (best_abs is None) or (diff < best_abs):
                best_abs = diff
                best_name = cname
                best_val = float(cval)

        if best_name is None:
            continue

        rel_err = best_abs / max(1e-12, abs(best_val)) if best_val != 0 else np.nan

        out = row.to_dict()
        out.update({
            "NearestConstant": best_name,
            "NearestConstantValue": best_val,
            "AbsDiffFromNearest": best_abs,
            "RelDiffFromNearest": rel_err,
            "MatchToleranceUsed": ATOL
        })
        rows.append(out)

    detailed_df = pd.DataFrame(rows)
    detailed_path = os.path.join(OUTPUT_DIR, "unmatched_ratios_detailed.csv")
    detailed_df.to_csv(detailed_path, index=False)
    print(f"Unmatched detailed table saved to {detailed_path}")

