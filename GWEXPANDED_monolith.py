def plot_classifier_roc_summary():
    """
    Summarize ROC AUC / accuracy from classifier_crossval_scores.csv
    and classifier_grouped_event_splits.csv.

    Expected columns (can be adjusted easily):
    - classifier_crossval_scores: SplitType ('random'), Fold, ROC_AUC, Accuracy
    - classifier_grouped_event_splits: SplitType ('grouped'), Fold, ROC_AUC, Accuracy
    """
    paths = [
        BASE_DIR / "classifier_crossval_scores.csv",
        BASE_DIR / "classifier_grouped_event_splits.csv",
    ]

    frames = []
    for p in paths:
        if not p.exists():
            print(f"[roc_summary] {p.name} not found, skipping.")
            continue
        df = pd.read_csv(p)
        frames.append(df)

    if not frames:
        print("[roc_summary] No classifier score CSVs found.")
        return

    df_all = pd.concat(frames, ignore_index=True)

    # Try to normalize column names
    if "SplitType" not in df_all.columns:
        if "split_type" in df_all.columns:
            df_all["SplitType"] = df_all["split_type"]
        else:
            df_all["SplitType"] = "unknown"

    if "ROC_AUC" not in df_all.columns:
        if "roc_auc" in df_all.columns:
            df_all["ROC_AUC"] = df_all["roc_auc"]

    if "Accuracy" not in df_all.columns:
        if "accuracy" in df_all.columns:
            df_all["Accuracy"] = df_all["accuracy"]

    metrics_needed = {"ROC_AUC", "Accuracy", "SplitType"}
    if not metrics_needed.issubset(df_all.columns):
        print("[roc_summary] Need ROC_AUC, Accuracy, SplitType columns.")
        print("Columns present:", list(df_all.columns))
        return

    # Boxplot of ROC_AUC and Accuracy by SplitType
    fig, ax = plt.subplots(figsize=(8, 5))
    df_melt = df_all.melt(
        id_vars="SplitType",
        value_vars=["ROC_AUC", "Accuracy"],
        var_name="Metric",
        value_name="Score",
    )
    sns.boxplot(data=df_melt, x="Metric", y="Score", hue="SplitType", ax=ax)
    ax.set_title("Classifier performance summary (ROC AUC / Accuracy)")
    fig.tight_layout()
    fig.savefig(OUT_DIR / "vis_classifier_roc_accuracy_summary.png")
    plt.close(fig)


