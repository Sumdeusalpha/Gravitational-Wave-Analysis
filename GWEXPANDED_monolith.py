def plot_event_on_vs_null_profiles(event_id="GW150914", detector="H1", top_n=20):
    """
    For a given event/detector, plot ON vs OFF/NULL constant profiles.
    Uses constant_matches_per_segment.csv.
    """
    path = BASE_DIR / "constant_matches_per_segment.csv"
    if not path.exists():
        print("[on_vs_null_profiles] constant_matches_per_segment.csv not found.")
        return

    df = pd.read_csv(path)
    needed = {"Event", "Detector", "Constant"}
    if not needed.issubset(df.columns):
        print("[on_vs_null_profiles] Need Event, Detector, Constant, SegmentType, count column.")
        print("Columns present:", list(df.columns))
        return

    # guess segment type column name
    seg_col = _pick_first_existing_column(df, ["SegmentType", "WindowType", "Class"])
    if seg_col is None:
        print("[on_vs_null_profiles] No SegmentType/WindowType/Class column.")
        print("Columns present:", list(df.columns))
        return

    count_col = _pick_first_existing_column(df, ["Matches", "TotalMatches", "Count"])
    if count_col is None:
        print("[on_vs_null_profiles] No Matches/TotalMatches/Count column.")
        print("Columns present:", list(df.columns))
        return

    mask = (df["Event"] == event_id) & (df["Detector"] == detector)
    sub = df[mask].copy()
    if sub.empty:
        print(f"[on_vs_null_profiles] No rows for Event={event_id}, Detector={detector}")
        return

    # aggregate by Constant x SegmentType
    agg = (
        sub.groupby(["Constant", seg_col])[count_col]
           .sum()
           .reset_index()
    )

    # choose top constants by ON count
    on_mask = agg[seg_col].isin(["ON", "On", "on"])
    if on_mask.any():
        on_counts = (
            agg[on_mask]
            .groupby("Constant")[count_col]
            .sum()
            .sort_values(ascending=False)
        )
        top_consts = on_counts.head(top_n).index.tolist()
        agg = agg[agg["Constant"].isin(top_consts)]
    else:
        # fallback: overall top_n
        overall = (
            agg.groupby("Constant")[count_col]
               .sum()
               .sort_values(ascending=False)
        )
        top_consts = overall.head(top_n).index.tolist()
        agg = agg[agg["Constant"].isin(top_consts)]

    fig, ax = plt.subplots(figsize=(10, 6))
    sns.barplot(
        data=agg,
        x="Constant",
        y=count_col,
        hue=seg_col,
        ax=ax,
    )
    ax.set_xticklabels(agg["Constant"].unique(), rotation=75, ha="right")
    ax.set_ylabel("Match count")
    ax.set_title(f"ON vs OFF / NULL constant profiles – {event_id} ({detector})")
    ax.legend(title=seg_col)
    fig.tight_layout()
    fname = f"vis_on_vs_null_profiles_{event_id}_{detector}.png"
    fig.savefig(OUT_DIR / fname)
    plt.close(fig)


